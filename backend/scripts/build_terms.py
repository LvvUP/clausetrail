NOT_DISEASE = re.compile(r"^(如何|我们|您|本合同|其他)")


def _split(s: str) -> list[str]:
    return [w for w in s.split() if w]


def extract_sample_diseases(path: Path) -> list[str]:
    if not path.exists():
        return []
    with pdfplumber.open(path) as pdf:
        text = "\n".join((pdf.pages[i].extract_text() or "") for i in range(min(4, len(pdf.pages))))
    names = set()
    for m in re.finditer(r"(?<![\d.])(\d{1,3})\.〔?([一-龥ⅠⅡⅢA-Za-z（）()]{3,18}?)〕?(?=——|\*|\s|$)", text):
        name = TRUNCATION_FIXES.get(m.group(2), m.group(2))
        name = re.sub(r"[（(][^）)]*[）)]?$", "", name).strip()
        if NOT_DISEASE.match(name) or re.search(r"[须或经且（(]$", name):
            continue
        if 3 <= len(name) <= 20:
            names.add(name)
    return sorted(names)


def main() -> int:
    rows: dict[str, tuple[str, str]] = {}
    for category, words in CURATED.items():
        for w in _split(words):
            rows.setdefault(w, (category, "curated"))
    for w in _split(STANDARD_CRITICAL_ILLNESS):
        rows.setdefault(w, ("重疾病种", "curated:中保协2020重疾定义规范病种名"))
    for w in extract_sample_diseases(SAMPLE):
        rows.setdefault(w, ("重疾病种", "samples:" + SAMPLE.name))

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with (OUT_DIR / "insurance_terms.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["term", "aliases", "category", "source"])
        for term, (category, source) in sorted(rows.items(), key=lambda kv: (kv[1][0], kv[0])):
            w.writerow([term, "|".join(ALIASES.get(term, [])), category, source])
    with (OUT_DIR / "synonyms.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["canonical", "alias"])
        for canonical, aliases in sorted(ALIASES.items()):
            for a in aliases:
                w.writerow([canonical, a])
    with (OUT_DIR / "ocr_confusions.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["char", "confusable"])
        w.writerows(OCR_CONFUSIONS)

    by_source: dict[str, int] = {}
    for _, source in rows.values():
        key = source.split(":")[0]
        by_source[key] = by_source.get(key, 0) + 1
    print(
        f"terms={len(rows)} by_source={by_source} "
        f"synonyms={sum(len(v) for v in ALIASES.values())} confusions={len(OCR_CONFUSIONS)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
